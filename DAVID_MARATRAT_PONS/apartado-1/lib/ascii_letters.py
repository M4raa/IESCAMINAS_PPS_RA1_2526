# Function to render text using the font above
# Parameters:
#   text: string to render
# Returns:
#   string with the rendered text

def render_text(text: str) -> str:
    text = text.upper()
    lines = ["" for _ in range(7)]

    for char in text:
        if char in ASCII_FONT:
            glyph = ASCII_FONT[char]
        else:
            glyph = [" " * 7] * 7
        while len(glyph) < 7:
            glyph.append(" " * len(glyph[0]))
        for i in range(7):
            lines[i] += glyph[i] + " "
    return "\n".join(lines)